/**
 * Calculates Nakshatra, Pada, and starting syllables for any given longitude [0, 360).
 */
export function getNakshatraFromLongitude(longitude: number): {
  nakshatra: NakshatraDefinition;
  pada: number;
  padaDetails: NakshatraDefinition['padas'][0];
  degreeInNakshatra: number;
  progressPercentage: number;
} {
  const span = 360 / 27; // 13.33333333 degrees
  const normalized = (longitude % 360 + 360) % 360;
  const index = Math.floor(normalized / span);
  const nakshatra = NAKSHATRAS[index % 27];

  const degInNakshatra = normalized - index * span;
  const padaSpan = span / 4; // 3.33333333 degrees
  const padaIndex = Math.min(3, Math.floor(degInNakshatra / padaSpan));
  const pada = padaIndex + 1;
  const padaDetails = nakshatra.padas[padaIndex];

  const progressPercentage = Math.round((degInNakshatra / span) * 100);

  return {
    nakshatra,
    pada,
    padaDetails,
    degreeInNakshatra: degInNakshatra,
    progressPercentage,
  };
}
