export function getTerm(category: 'planet' | 'sign' | 'house', key: string | number, lang: LanguageCode): string {
  if (category === 'planet') {
    const term = PLANET_TERMS[key as PlanetName];
    return term ? (term as any)[lang] || term.en : String(key);
  }
  if (category === 'sign') {
    const term = SIGN_TERMS[key as ZodiacSignName];
    return term ? (term as any)[lang] || term.en : String(key);
  }
  if (category === 'house') {
    const term = HOUSE_TERMS[Number(key)];
    return term ? (term as any)[lang] || term.en : `House ${key}`;
  }
  return String(key);
}
