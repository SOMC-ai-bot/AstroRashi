const EXTRA_DICTIONARIES: Record<string, Partial<Record<LanguageCode, string>>>[] = [];

/**
 * Register additional translation dictionaries dynamically without circular dependencies.
 */
export function registerTranslationDictionary(dict: Record<string, Partial<Record<LanguageCode, string>>>) {
  if (dict && !EXTRA_DICTIONARIES.includes(dict)) {
    EXTRA_DICTIONARIES.push(dict);
  }
}

/**
 * Universal UI translation function that looks up known phrases
 * or returns original string if no match is found.
 */
export function tUI(text: string, lang: LanguageCode): string {
  if (!text) return '';
  if (lang === 'en') return text;
  
  const trimmed = text.trim();

  // 1. Exact match lookup in UI_TRANSLATIONS
  if (UI_TRANSLATIONS[trimmed] && UI_TRANSLATIONS[trimmed][lang]) {
    return text === trimmed ? UI_TRANSLATIONS[trimmed][lang] : text.replace(trimmed, UI_TRANSLATIONS[trimmed][lang]);
  }

  // 2. Exact match in registered extra dictionaries
  for (let i = 0; i < EXTRA_DICTIONARIES.length; i++) {
    const entry = EXTRA_DICTIONARIES[i][trimmed];
    if (entry && entry[lang]) {
      return text === trimmed ? entry[lang]! : text.replace(trimmed, entry[lang]!);
    }
  }

  // 3. Fallback to Hindi if target language is Hinglish, Punjabi, or Urdu and Hindi entry exists
  if (lang === 'hinglish' || lang === 'pa' || lang === 'ur') {
    if (UI_TRANSLATIONS[trimmed] && UI_TRANSLATIONS[trimmed]['hi']) {
      return text === trimmed ? UI_TRANSLATIONS[trimmed]['hi'] : text.replace(trimmed, UI_TRANSLATIONS[trimmed]['hi']);
    }
    for (let i = 0; i < EXTRA_DICTIONARIES.length; i++) {
      const entry = EXTRA_DICTIONARIES[i][trimmed];
      if (entry && entry['hi']) {
        return text === trimmed ? entry['hi']! : text.replace(trimmed, entry['hi']!);
      }
    }
  }

  return text;
}

